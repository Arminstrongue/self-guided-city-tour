/** Substitui {chaves} no texto. */
export function fmt(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.split(`{${k}}`).join(String(v)), s);
}
